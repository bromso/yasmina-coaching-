/*
 * The two committed files, rendered from the token list. Pure apart from `readTokens()`, and free
 * of style-dictionary, so `scripts/tokens.test.ts` can regenerate them in CI's planner job, which
 * runs before `bun install`. style-dictionary drives the same functions (`./generate.ts`), and
 * `./tokens.test.ts` pins that both ways give the same output.
 *
 * A colour token's dark value sits in `$extensions.mode.dark`; a colour without one, like every
 * other token, is the same in both themes and is written under `:root` only. Tokens under `email`
 * reach only the email file. A value may reference another token as `{group.name}`, resolved as
 * style-dictionary resolves it.
 */
import { readdirSync, readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { parseOklch, toHex } from "./color"

const local = (relative: string) => fileURLToPath(new URL(relative, import.meta.url))

/** Where each generated file is committed. */
export const OUTPUTS = {
  css: local("../../ui/src/styles/tokens.generated.css"),
  email: local("../../email/src/tokens.generated.ts"),
} as const

/** One token: its path in the JSON, its (light) value and, for a colour, any dark value. */
export type Token = { path: string[]; value: string; dark?: string }

const NOTE = "Generated by packages/tokens from src/tokens: do not edit. Run `bun run tokens`."

const isEmail = (token: Token) => token.path[0] === "email"
const isColor = (token: Token) => token.path[0] === "color"

/** `color.card-foreground` → `card-foreground`, `shadow.DEFAULT` → `shadow`, `font.sans` → `font-sans`. */
export function cssName(path: string[]): string {
  return (path[0] === "color" ? path.slice(1) : path)
    .filter((segment) => segment !== "DEFAULT")
    .join("-")
}

/** The theme stylesheet: `:root` for the light theme, `.dark` for the dark one, in `oklch()`. */
export function renderTheme(tokens: Token[]): string {
  const css = tokens.filter((token) => !isEmail(token))
  for (const token of css) {
    if (!isColor(token) && token.dark !== undefined) {
      throw new Error(`${token.path.join(".")} is not a colour, so it cannot have a dark value`)
    }
  }
  const block = (selector: string, lines: string[]) => `${selector} {\n${lines.join("\n")}\n}\n`
  const light = css.map((token) => `  --${cssName(token.path)}: ${token.value};`)
  const dark = css
    .filter((token) => token.dark !== undefined)
    .map((token) => `  --${cssName(token.path)}: ${token.dark};`)
  return `/* ${NOTE} */\n${block(":root", light)}\n${block(".dark", dark)}`
}

/** The colours the email templates use, keyed as they name them. */
const EMAIL_COLOR_TOKENS = {
  background: "background",
  foreground: "foreground",
  muted: "muted",
  mutedForeground: "muted-foreground",
  primary: "primary",
  primaryForeground: "primary-foreground",
  border: "border",
  brandBlue: "brand-blue",
  sun: "sun",
  sunSoft: "sun-soft",
} as const

/** The email constants: the light palette as sRGB hex (mail clients read no `oklch()`), the fonts. */
export function renderEmail(tokens: Token[]): string {
  const value = (...path: string[]) => {
    const token = tokens.find((candidate) => candidate.path.join(".") === path.join("."))
    if (!token) throw new Error(`no token ${path.join(".")}`)
    return token.value
  }
  const colors = Object.entries(EMAIL_COLOR_TOKENS).map(
    ([key, name]) => `  ${key}: "${toHex(parseOklch(value("color", name)))}",`
  )
  // Single quotes around a stack that quotes a family name, as Biome would write it.
  const quote = (text: string) => (text.includes('"') ? `'${text}'` : JSON.stringify(text))
  const fonts = ["display", "body"].map((key) => `  ${key}: ${quote(value("email", "font", key))},`)
  return [
    `// ${NOTE}`,
    "",
    "export type EmailColor =",
    ...Object.keys(EMAIL_COLOR_TOKENS).map((key) => `  | "${key}"`),
    "",
    "/** The light theme's colours as sRGB hex: mail clients do not read `oklch()`. */",
    "export const EMAIL_COLORS: Record<EmailColor, string> = {",
    ...colors,
    "}",
    "",
    "/** Headings in the display serif's own fallback, body text in the system sans. */",
    "export const EMAIL_FONTS = {",
    ...fonts,
    "} as const",
    "",
  ].join("\n")
}

const REFERENCE = /\{([^{}]+)\}/g

/**
 * Every token in `src/tokens/*.json`, files in name order, as style-dictionary reads them, with
 * `{group.name}` references in `$value` replaced by the referenced token's (resolved) value.
 */
export function readTokens(dir = local("./tokens")): Token[] {
  const tokens: Token[] = []
  const walk = (node: Record<string, unknown>, path: string[]) => {
    if ("$value" in node) {
      const dark = (node.$extensions as { mode?: { dark?: string } } | undefined)?.mode?.dark
      tokens.push({ path, value: String(node.$value), ...(dark === undefined ? {} : { dark }) })
      return
    }
    for (const [key, child] of Object.entries(node)) {
      if (!key.startsWith("$") && child && typeof child === "object") {
        walk(child as Record<string, unknown>, [...path, key])
      }
    }
  }
  for (const file of readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .sort()) {
    walk(JSON.parse(readFileSync(`${dir}/${file}`, "utf8")), [])
  }
  const byPath = new Map(tokens.map((token) => [token.path.join("."), token]))
  const resolve = (text: string, from: string, seen: string[]): string =>
    text.replace(REFERENCE, (_, ref: string) => {
      const target = byPath.get(ref)
      if (!target) throw new Error(`${from} refers to {${ref}}, which is not a token`)
      if (seen.includes(ref)) throw new Error(`${from} refers to itself through {${ref}}`)
      return resolve(target.value, ref, [...seen, ref])
    })
  return tokens.map((token) => {
    const name = token.path.join(".")
    const resolved: Token = { ...token, value: resolve(token.value, name, [name]) }
    // style-dictionary resolves `$value` only, so a dark reference would differ between the two.
    if (token.dark?.match(REFERENCE)) {
      throw new Error(`${name}: references are not supported in $extensions.mode.dark`)
    }
    return resolved
  })
}

/** Both committed files' contents, rendered from `src/tokens` without style-dictionary. */
export function render(tokens = readTokens()): { css: string; email: string } {
  return { css: renderTheme(tokens), email: renderEmail(tokens) }
}
